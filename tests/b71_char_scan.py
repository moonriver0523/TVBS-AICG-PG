def scan() -> tuple[list[tuple[str, str, str]], list[tuple[str, str, str]]]:
    """回傳 (present, missing)，各為 (簡體, 繁體, 常見詞) 的清單，簡體字去重。"""
    seen: set[str] = set()
    present: list[tuple[str, str, str]] = []
    missing: list[tuple[str, str, str]] = []
    for simp, trad, word in CANDIDATES:
        if simp == trad or simp in seen:
            continue
        seen.add(simp)
        (present if simp in main.DIGEST_NON_TW_CHARS else missing).append((simp, trad, word))
    return present, missing


if __name__ == "__main__":
    present, missing = scan()
